-- ============================================================

-- 1. Course catalogue
CREATE TABLE course (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                        course_code VARCHAR(20) NOT NULL,
                        title VARCHAR(150) NOT NULL,
                        credits INTEGER NOT NULL,
                        department_id BIGINT NOT NULL,
                        active BOOLEAN NOT NULL DEFAULT TRUE,

                        CONSTRAINT uq_course_code
                            UNIQUE (course_code),

                        CONSTRAINT ck_course_credits
                            CHECK (credits > 0),

                        CONSTRAINT fk_course_department
                            FOREIGN KEY (department_id)
                                REFERENCES department(id)
                                ON DELETE RESTRICT
);

CREATE INDEX idx_course_department_id
    ON course(department_id);

-- 2. Course prerequisites
CREATE TABLE course_prerequisite (
                                     course_id BIGINT NOT NULL,
                                     prerequisite_course_id BIGINT NOT NULL,

                                     CONSTRAINT pk_course_prerequisite
                                         PRIMARY KEY (course_id, prerequisite_course_id),

                                     CONSTRAINT fk_course_prerequisite_course
                                         FOREIGN KEY (course_id)
                                             REFERENCES course(id)
                                             ON DELETE RESTRICT,

                                     CONSTRAINT fk_course_prerequisite_required
                                         FOREIGN KEY (prerequisite_course_id)
                                             REFERENCES course(id)
                                             ON DELETE RESTRICT,

                                     CONSTRAINT ck_course_not_own_prerequisite
                                         CHECK (course_id <> prerequisite_course_id)
);

CREATE INDEX idx_course_prerequisite_required
    ON course_prerequisite(prerequisite_course_id);