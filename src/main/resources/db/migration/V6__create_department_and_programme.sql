CREATE TABLE department (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(20) NOT NULL,
    name VARCHAR(100) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT uq_department_code UNIQUE (code),
    CONSTRAINT uq_department_name UNIQUE (name)
);

CREATE TABLE programme (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(20) NOT NULL,
    name VARCHAR(150) NOT NULL,
    department_id BIGINT NOT NULL,
    duration_years SMALLINT NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT uq_programme_code UNIQUE (code),
    CONSTRAINT ck_programme_duration
        CHECK (duration_years > 0),
    CONSTRAINT fk_programme_department
        FOREIGN KEY (department_id)
        REFERENCES department(id)
        ON DELETE RESTRICT
);

CREATE INDEX idx_programme_department_id
    ON programme(department_id);

