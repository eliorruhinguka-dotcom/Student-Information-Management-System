CREATE TABLE semester (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    academic_year VARCHAR(9) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    max_credit_load SMALLINT NOT NULL,

    CONSTRAINT uq_semester_name_academic_year
        UNIQUE (name, academic_year),

    CONSTRAINT ck_semester_dates
        CHECK (end_date >= start_date),

    CONSTRAINT ck_semester_max_credit_load
        CHECK (max_credit_load > 0)
);

CREATE TABLE registration_period (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    semester_id BIGINT NOT NULL,
    opens_at TIMESTAMPTZ NOT NULL,
    closes_at TIMESTAMPTZ NOT NULL,
    status VARCHAR(10) NOT NULL DEFAULT 'SCHEDULED',
    opened_by BIGINT,
    closed_by BIGINT,
    closed_at TIMESTAMPTZ,

    CONSTRAINT fk_registration_period_semester
        FOREIGN KEY (semester_id)
        REFERENCES semester(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_registration_period_opened_by
        FOREIGN KEY (opened_by)
        REFERENCES user_accounts(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_registration_period_closed_by
        FOREIGN KEY (closed_by)
        REFERENCES user_accounts(id)
        ON DELETE RESTRICT,

    CONSTRAINT ck_registration_period_dates
        CHECK (closes_at > opens_at),

    CONSTRAINT ck_registration_period_status
        CHECK (status IN ('SCHEDULED', 'OPEN', 'CLOSED'))
);

CREATE INDEX idx_registration_period_semester
    ON registration_period(semester_id);

CREATE UNIQUE INDEX uq_registration_period_one_open
    ON registration_period(semester_id)
    WHERE status = 'OPEN';