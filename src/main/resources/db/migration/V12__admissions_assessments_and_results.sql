-- V12: Admission applications, student profile history, assessments and results.
-- Applied migrations V1-V11 are intentionally left unchanged.

-- Student data model extension. Existing records are mapped to the approved
-- UNASSIGNED programme instead of inventing personal data such as date of birth.
ALTER TABLE student RENAME COLUMN student_number TO registration_number;
ALTER TABLE student
    ADD COLUMN programme_id BIGINT,
    ADD COLUMN date_of_birth DATE,
    ADD COLUMN national_id VARCHAR(30),
    ADD COLUMN admitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ADD COLUMN version BIGINT NOT NULL DEFAULT 0;

UPDATE student
SET programme_id = (SELECT id FROM programme WHERE code = 'UNASSIGNED' LIMIT 1)
WHERE programme_id IS NULL;

ALTER TABLE student
    ALTER COLUMN programme_id SET NOT NULL,
    ADD CONSTRAINT fk_student_programme
        FOREIGN KEY (programme_id) REFERENCES programme(id) ON DELETE RESTRICT;

CREATE UNIQUE INDEX uq_student_email_lower ON student (LOWER(email));
CREATE UNIQUE INDEX uq_student_national_id
    ON student (national_id) WHERE national_id IS NOT NULL;
CREATE INDEX idx_student_programme_status ON student (programme_id, status);
CREATE INDEX idx_student_last_name_lower ON student (LOWER(last_name));
CREATE INDEX idx_student_first_name_lower ON student (LOWER(first_name));

-- Keep the older /api/students creation route functional while callers transition to /api/v1.
-- It assigns the seeded fallback programme when that legacy payload omits programmeId.
CREATE OR REPLACE FUNCTION assign_unassigned_student_programme()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.programme_id IS NULL THEN
        SELECT id INTO NEW.programme_id FROM programme WHERE code = 'UNASSIGNED' LIMIT 1;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER trg_student_assign_unassigned_programme
    BEFORE INSERT ON student
    FOR EACH ROW EXECUTE FUNCTION assign_unassigned_student_programme();

CREATE SEQUENCE student_reg_seq START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE admission_application_ref_seq START WITH 1 INCREMENT BY 1;

-- Student status history is append-only.
CREATE TABLE student_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL,
    from_status VARCHAR(20) NOT NULL,
    to_status VARCHAR(20) NOT NULL,
    reason TEXT NOT NULL,
    changed_by BIGINT NOT NULL,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_student_status_history_student
        FOREIGN KEY (student_id) REFERENCES student(id) ON DELETE RESTRICT,
    CONSTRAINT fk_student_status_history_actor
        FOREIGN KEY (changed_by) REFERENCES user_accounts(id) ON DELETE RESTRICT,
    CONSTRAINT ck_student_status_history_change CHECK (from_status <> to_status)
);
CREATE INDEX idx_student_status_history_student
    ON student_status_history(student_id, changed_at DESC);

CREATE OR REPLACE FUNCTION prevent_student_status_history_mutation()
RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION 'student_status_history is append-only';
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER trg_student_status_history_no_mutation
    BEFORE UPDATE OR DELETE ON student_status_history
    FOR EACH ROW EXECUTE FUNCTION prevent_student_status_history_mutation();

-- Public admission applications. An applicant has no student record until approval.
CREATE TABLE admission_application (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference VARCHAR(20) NOT NULL UNIQUE,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    email VARCHAR(100) NOT NULL,
    date_of_birth DATE NOT NULL,
    national_id VARCHAR(30),
    programme_id BIGINT NOT NULL,
    status VARCHAR(12) NOT NULL DEFAULT 'SUBMITTED',
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_by BIGINT,
    reviewed_at TIMESTAMPTZ,
    decision_reason TEXT,
    student_id BIGINT UNIQUE,
    ip_address VARCHAR(45),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_admission_application_programme
        FOREIGN KEY (programme_id) REFERENCES programme(id) ON DELETE RESTRICT,
    CONSTRAINT fk_admission_application_reviewer
        FOREIGN KEY (reviewed_by) REFERENCES user_accounts(id) ON DELETE RESTRICT,
    CONSTRAINT fk_admission_application_student
        FOREIGN KEY (student_id) REFERENCES student(id) ON DELETE RESTRICT,
    CONSTRAINT ck_admission_application_status
        CHECK (status IN ('SUBMITTED', 'APPROVED', 'REJECTED')),
    CONSTRAINT ck_admission_application_decision
        CHECK (
            (status = 'SUBMITTED' AND reviewed_by IS NULL AND reviewed_at IS NULL AND student_id IS NULL)
            OR (status = 'APPROVED' AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL AND student_id IS NOT NULL)
            OR (status = 'REJECTED' AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL
                AND decision_reason IS NOT NULL AND length(trim(decision_reason)) > 0 AND student_id IS NULL)
        )
);
CREATE UNIQUE INDEX uq_admission_application_open_email
    ON admission_application(LOWER(email)) WHERE status = 'SUBMITTED';
CREATE INDEX idx_admission_application_status_submitted
    ON admission_application(status, submitted_at DESC);
CREATE INDEX idx_admission_application_programme ON admission_application(programme_id);

-- Assessments and scores.
CREATE TABLE assessment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_offering_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    type VARCHAR(20) NOT NULL,
    max_mark NUMERIC(5,2) NOT NULL,
    weight_percent NUMERIC(5,2) NOT NULL,
    created_by BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_assessment_offering
        FOREIGN KEY (course_offering_id) REFERENCES course_offerings(id) ON DELETE RESTRICT,
    CONSTRAINT fk_assessment_creator
        FOREIGN KEY (created_by) REFERENCES user_accounts(id) ON DELETE RESTRICT,
    CONSTRAINT uq_assessment_offering_name UNIQUE(course_offering_id, name),
    CONSTRAINT ck_assessment_type
        CHECK (type IN ('ASSIGNMENT', 'TEST', 'QUIZ', 'PROJECT', 'FINAL_EXAM')),
    CONSTRAINT ck_assessment_max_mark CHECK (max_mark > 0),
    CONSTRAINT ck_assessment_weight CHECK (weight_percent > 0 AND weight_percent <= 100)
);
CREATE INDEX idx_assessment_offering ON assessment(course_offering_id);

CREATE TABLE assessment_score (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assessment_id BIGINT NOT NULL,
    course_registration_id BIGINT NOT NULL,
    mark NUMERIC(5,2),
    entered_by BIGINT NOT NULL,
    entered_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_assessment_score_assessment
        FOREIGN KEY (assessment_id) REFERENCES assessment(id) ON DELETE RESTRICT,
    CONSTRAINT fk_assessment_score_registration
        FOREIGN KEY (course_registration_id) REFERENCES course_registrations(id) ON DELETE RESTRICT,
    CONSTRAINT fk_assessment_score_entered_by
        FOREIGN KEY (entered_by) REFERENCES user_accounts(id) ON DELETE RESTRICT,
    CONSTRAINT uq_assessment_score_registration UNIQUE(assessment_id, course_registration_id),
    CONSTRAINT ck_assessment_score_nonnegative CHECK (mark IS NULL OR mark >= 0)
);
CREATE INDEX idx_assessment_score_registration ON assessment_score(course_registration_id);

CREATE OR REPLACE FUNCTION touch_assessment_score_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER trg_assessment_score_updated_at
    BEFORE UPDATE ON assessment_score
    FOR EACH ROW EXECUTE FUNCTION touch_assessment_score_updated_at();

-- Grade scale and result tables are created now because result calculation depends on them.
-- No institutional grade bands are invented here. The four grade-scale endpoints in a later batch
-- will allow the university to configure and activate its actual grading policy.
CREATE TABLE grade_scale (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    active BOOLEAN NOT NULL DEFAULT FALSE,
    effective_from DATE NOT NULL
);
CREATE UNIQUE INDEX uq_grade_scale_one_active ON grade_scale(active) WHERE active = TRUE;

CREATE TABLE grade_scale_band (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grade_scale_id BIGINT NOT NULL,
    min_mark NUMERIC(5,2) NOT NULL,
    max_mark NUMERIC(5,2) NOT NULL,
    grade VARCHAR(3) NOT NULL,
    grade_points NUMERIC(3,2) NOT NULL,
    is_pass BOOLEAN NOT NULL,
    CONSTRAINT fk_grade_scale_band_scale
        FOREIGN KEY (grade_scale_id) REFERENCES grade_scale(id) ON DELETE RESTRICT,
    CONSTRAINT ck_grade_scale_band_range
        CHECK (min_mark >= 0 AND max_mark <= 100 AND min_mark <= max_mark),
    CONSTRAINT ck_grade_scale_band_points CHECK (grade_points >= 0)
);
CREATE INDEX idx_grade_scale_band_scale ON grade_scale_band(grade_scale_id);

CREATE TABLE result (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_registration_id BIGINT NOT NULL UNIQUE,
    final_mark NUMERIC(5,2),
    grade VARCHAR(3),
    passed BOOLEAN,
    grade_scale_id BIGINT,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    submitted_by BIGINT,
    submitted_at TIMESTAMPTZ,
    approved_by BIGINT,
    approved_at TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_result_registration
        FOREIGN KEY (course_registration_id) REFERENCES course_registrations(id) ON DELETE RESTRICT,
    CONSTRAINT fk_result_grade_scale
        FOREIGN KEY (grade_scale_id) REFERENCES grade_scale(id) ON DELETE RESTRICT,
    CONSTRAINT fk_result_submitted_by
        FOREIGN KEY (submitted_by) REFERENCES user_accounts(id) ON DELETE RESTRICT,
    CONSTRAINT fk_result_approved_by
        FOREIGN KEY (approved_by) REFERENCES user_accounts(id) ON DELETE RESTRICT,
    CONSTRAINT ck_result_status CHECK (status IN ('DRAFT', 'SUBMITTED', 'PUBLISHED')),
    CONSTRAINT ck_result_final_mark CHECK (final_mark IS NULL OR final_mark BETWEEN 0 AND 100),
    CONSTRAINT ck_result_submitted_metadata
        CHECK (status = 'DRAFT' OR (submitted_by IS NOT NULL AND submitted_at IS NOT NULL)),
    CONSTRAINT ck_result_published_metadata
        CHECK (status <> 'PUBLISHED' OR (approved_by IS NOT NULL AND approved_at IS NOT NULL))
);
CREATE INDEX idx_result_status ON result(status);

CREATE TABLE result_correction (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    result_id BIGINT NOT NULL,
    original_mark NUMERIC(5,2) NOT NULL,
    corrected_mark NUMERIC(5,2) NOT NULL,
    original_grade VARCHAR(3) NOT NULL,
    corrected_grade VARCHAR(3) NOT NULL,
    reason TEXT NOT NULL,
    requested_by BIGINT,
    authorised_by BIGINT NOT NULL,
    corrected_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_result_correction_result
        FOREIGN KEY (result_id) REFERENCES result(id) ON DELETE RESTRICT,
    CONSTRAINT fk_result_correction_requester
        FOREIGN KEY (requested_by) REFERENCES user_accounts(id) ON DELETE RESTRICT,
    CONSTRAINT fk_result_correction_authoriser
        FOREIGN KEY (authorised_by) REFERENCES user_accounts(id) ON DELETE RESTRICT,
    CONSTRAINT ck_result_correction_mark CHECK (original_mark <> corrected_mark),
    CONSTRAINT ck_result_correction_reason CHECK (length(trim(reason)) > 0)
);
CREATE INDEX idx_result_correction_result ON result_correction(result_id, corrected_at DESC);

CREATE OR REPLACE FUNCTION prevent_result_correction_mutation()
RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION 'result_correction is append-only';
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER trg_result_correction_no_mutation
    BEFORE UPDATE OR DELETE ON result_correction
    FOR EACH ROW EXECUTE FUNCTION prevent_result_correction_mutation();
