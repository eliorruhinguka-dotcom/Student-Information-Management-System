                                           ON DELETE RESTRICT,

                                   CONSTRAINT fk_student_user_link_student
                                       FOREIGN KEY (student_id)
                                           REFERENCES student(id)
                                           ON DELETE RESTRICT
);

INSERT INTO student_user_link (user_id, student_id)
