-- 7. Extend existing user accounts
ALTER TABLE user_accounts
    ADD COLUMN full_name VARCHAR(150),
    ADD COLUMN department_id BIGINT,
    ADD COLUMN failed_login_count INTEGER NOT NULL DEFAULT 0,
    ADD COLUMN locked_until TIMESTAMPTZ,
    ADD COLUMN last_login_at TIMESTAMPTZ,
    ADD COLUMN updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ADD COLUMN created_by BIGINT,
    ADD COLUMN version BIGINT NOT NULL DEFAULT 0,
    ADD COLUMN must_change_password BOOLEAN NOT NULL DEFAULT FALSE;

-- Preserve existing account names where a student link exists.
-- Staff accounts without a student link use their email prefix.
UPDATE user_accounts ua
SET full_name = COALESCE(
        NULLIF(
                TRIM(CONCAT_WS(' ', s.first_name, s.last_name)),
                ''
        ),
        NULLIF(SPLIT_PART(ua.email, '@', 1), ''),
        ua.email
                )
    FROM student s
WHERE s.id = ua.student_id;

UPDATE user_accounts
SET full_name = COALESCE(
        NULLIF(SPLIT_PART(email, '@', 1), ''),
        email
                )
WHERE full_name IS NULL;

ALTER TABLE user_accounts
    ALTER COLUMN full_name SET NOT NULL,
ALTER COLUMN email TYPE VARCHAR(150);

-- Remove the old case-sensitive unique constraint before adding
-- the case-insensitive unique index.
ALTER TABLE user_accounts
DROP CONSTRAINT user_accounts_email_key;

-- Case-insensitive unique account email
CREATE UNIQUE INDEX uq_user_accounts_email_lower
    ON user_accounts (LOWER(email));

-- Department scope for lecturers and deans
ALTER TABLE user_accounts
    ADD CONSTRAINT fk_user_accounts_department
        FOREIGN KEY (department_id)
            REFERENCES department(id)
            ON DELETE RESTRICT;

-- Self-reference for account creator
ALTER TABLE user_accounts
    ADD CONSTRAINT fk_user_accounts_created_by
        FOREIGN KEY (created_by)
            REFERENCES user_accounts(id)
            ON DELETE RESTRICT;

-- Keep updated_at current whenever an account changes
CREATE OR REPLACE FUNCTION update_user_account_timestamp()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_user_accounts_updated_at
    BEFORE UPDATE ON user_accounts
    FOR EACH ROW
    EXECUTE FUNCTION update_user_account_timestamp();

-- 8. Replace the old single-role field with user_role
CREATE TABLE user_role (
                           user_id BIGINT NOT NULL,
                           role_id BIGINT NOT NULL,

                           CONSTRAINT pk_user_role
                               PRIMARY KEY (user_id, role_id),

                           CONSTRAINT fk_user_role_user
                               FOREIGN KEY (user_id)
                                   REFERENCES user_accounts(id)
                                   ON DELETE RESTRICT,

                           CONSTRAINT fk_user_role_role
                               FOREIGN KEY (role_id)
                                   REFERENCES "role"(id)
                                   ON DELETE RESTRICT
);

-- Transfer existing single-role assignments before removing the old column.
INSERT INTO user_role (user_id, role_id)
SELECT ua.id, r.id
FROM user_accounts ua
         JOIN "role" r ON r.name = ua.role;

-- 9. Replace the direct student_id field with student_user_link
CREATE TABLE student_user_link (
                                   user_id BIGINT PRIMARY KEY,
                                   student_id BIGINT NOT NULL UNIQUE,

                                   CONSTRAINT fk_student_user_link_user
                                       FOREIGN KEY (user_id)
