-- 10. Hashed, revocable and rotating refresh tokens
CREATE TABLE refresh_token (
                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               user_id BIGINT NOT NULL,
                               token_hash CHAR(64) NOT NULL UNIQUE,
                               issued_at TIMESTAMPTZ NOT NULL,
                               expires_at TIMESTAMPTZ NOT NULL,
                               revoked_at TIMESTAMPTZ,

                               CONSTRAINT fk_refresh_token_user
                                   FOREIGN KEY (user_id)
                                       REFERENCES user_accounts(id)
                                       ON DELETE RESTRICT,

                               CONSTRAINT ck_refresh_token_dates
                                   CHECK (expires_at > issued_at)
);

CREATE INDEX idx_refresh_token_user
    ON refresh_token(user_id);

CREATE INDEX idx_refresh_token_expiry
    ON refresh_token(expires_at);

-- 11. Audit log
CREATE TABLE audit_log (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                           actor_user_id BIGINT,
                           action VARCHAR(60) NOT NULL,
                           entity_type VARCHAR(60),
                           entity_id BIGINT,
                           old_value JSONB,
                           new_value JSONB,
                           outcome VARCHAR(10) NOT NULL,
                           ip_address VARCHAR(45),
                           correlation_id VARCHAR(64),

                           CONSTRAINT fk_audit_log_actor
                               FOREIGN KEY (actor_user_id)
                                   REFERENCES user_accounts(id)
                                   ON DELETE RESTRICT,

                           CONSTRAINT ck_audit_log_outcome
                               CHECK (outcome IN ('SUCCESS', 'DENIED', 'FAILED'))
);

CREATE INDEX idx_audit_log_actor_occurred
    ON audit_log(actor_user_id, occurred_at);

CREATE INDEX idx_audit_log_entity
    ON audit_log(entity_type, entity_id);

-- 12. Make audit_log append-only at database level
CREATE OR REPLACE FUNCTION prevent_audit_log_mutation()
RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION 'audit_log is append-only';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_audit_log_no_update
    BEFORE UPDATE OR DELETE ON audit_log
FOR EACH ROW
EXECUTE FUNCTION prevent_audit_log_mutation();